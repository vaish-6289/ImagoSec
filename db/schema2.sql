-- IMAGOSEC RELATIONAL SCHEMA DESIGN (RDBMS ALIGNMENT PROOF)
CREATE TABLE Users (
    UserID INT IDENTITY(1,1) PRIMARY KEY,
    UserPrincipalName NVARCHAR(256) NOT NULL UNIQUE,
    CreatedDate DATETIME DEFAULT GETDATE()
);

CREATE TABLE AnalysisLogs (
    LogID INT IDENTITY(1,1) PRIMARY KEY,
    UserID INT NULL,
    Filename NVARCHAR(512) NOT NULL,
    FileHash NVARCHAR(64) NOT NULL,
    ThreatLevel NVARCHAR(50) NOT NULL,
    Timestamp DATETIME DEFAULT GETDATE(),
    CONSTRAINT FK_AnalysisLogs_Users FOREIGN KEY (UserID) REFERENCES Users(UserID) ON DELETE SET NULL
);

CREATE INDEX IX_AnalysisLogs_ThreatLevel ON AnalysisLogs(ThreatLevel);
